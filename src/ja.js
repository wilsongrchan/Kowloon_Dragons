const JA_RUBY = [
  ['門前幺九龍', '<ruby>門前幺九龍<rt>メンゼンヤオチューロン</rt></ruby>'], ['門前幺九順', '<ruby>門前幺九順<rt>メンゼンヤオチュージュン</rt></ruby>'],
  ['幺九龍', '<ruby>幺九龍<rt>ヤオチューロン</rt></ruby>'], ['幺九順', '<ruby>幺九順<rt>ヤオチュージュン</rt></ruby>'],
  ['無役翻', '<ruby>無役翻<rt>むやくはん</rt></ruby>'],
  ['彩雀頭', '<ruby>彩雀頭<rt>さいジャントウ</rt></ruby>'], ['彩刻子', '<ruby>彩刻子<rt>さいコーツ</rt></ruby>'],
  ['彩ポン', '<ruby>彩<rt>さい</rt></ruby>ポン'], ['彩チー', '<ruby>彩<rt>さい</rt></ruby>チー'],
  ['不求人', '<ruby>不求人<rt>プーチウレン</rt></ruby>'], ['全大字', '<ruby>全大字<rt>ぜんだいじ</rt></ruby>'], ['断大字', '<ruby>断大字<rt>だんだいじ</rt></ruby>'],
  ['大字牌', '<ruby>大字牌<rt>だいじはい</rt></ruby>'], ['小字牌', '<ruby>小字牌<rt>しょうじはい</rt></ruby>'],
];
const JA_RUBY_RX = new RegExp(JA_RUBY.map(x => x[0]).sort((a, b) => b.length - a.length).join('|'), 'g');
function jaRuby(html) {
  const used = new Set(), map = new Map(JA_RUBY);
  return html.split(/(<[^>]*>)/).map(part => part.startsWith('<') ? part : part.replace(JA_RUBY_RX, t => (used.has(t) ? t : (used.add(t), map.get(t))))).join('');
}
